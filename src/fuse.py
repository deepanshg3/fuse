# ============================================================
# LOAD FILE SUMMARIES
# ============================================================

def load_file_summaries():
    """
    Load the Level 2 file summaries generated during
    the first semantic enrichment stage.
    """

    summary_file = Path(
        "data/summaries.json"
    )

    if not summary_file.exists():
        raise RuntimeError(
            "data/summaries.json was not generated."
        )

    with summary_file.open(
        "r",
        encoding="utf-8",
    ) as f:

        return json.load(f)


# ============================================================
# MODULE ENRICHMENT
# ============================================================

def enrich_modules(
    graph,
):
    """
    Generate Level 1 module summaries after all
    Level 2 file summaries are available.
    """

    print()
    print(
        "[FUSE] Starting module-level semantic enrichment..."
    )

    summaries = load_file_summaries()

    modules = get_modules(
        graph
    )

    print(
        f"[FUSE] Found {len(modules)} modules"
    )

    results = []

    for index, module_name in enumerate(
        modules,
        start=1,
    ):

        file_summaries = get_module_file_summaries(
            graph,
            module_name,
            summaries,
        )

        if not file_summaries:

            print(
                f"[{index}/{len(modules)}] "
                f"module:{module_name} "
                "✗ NO FILE SUMMARIES"
            )

            results.append({
                "status": "failed",
                "module": module_name,
                "error": (
                    "No Level 2 file summaries "
                    "found for module."
                ),
            })

            continue

        result = process_module(
            module_name,
            file_summaries,
            index,
            len(modules),
        )

        results.append(
            result
        )

    return results


# ============================================================
# ORCHESTRATOR
# ============================================================

def run():

    print("=" * 60)
    print(
        "FUSE — CODEBASE KNOWLEDGE GRAPH BUILDER"
    )
    print("=" * 60)

    # --------------------------------------------------------
    # 1. DISCOVER REPOSITORY
    # --------------------------------------------------------

    files = discover_files()

    print(
        f"[FUSE] Found {len(files)} Python files"
    )

    if not files:

        raise RuntimeError(
            f"No Python files found in {REPO_ROOT}"
        )

    print()

    # --------------------------------------------------------
    # 2. BUILD STRUCTURAL GRAPH
    # --------------------------------------------------------

    graph = initialize_graph()

    print()

    # --------------------------------------------------------
    # 3. LEVEL 2 + LEVEL 3
    # --------------------------------------------------------

    print(
        "[FUSE] Starting file/symbol semantic enrichment..."
    )

    start_time = time.time()

    file_results = []

    for index, file_path in enumerate(
        files,
        start=1,
    ):

        result = process_file(
            file_path,
            index,
            len(files),
            graph,
        )

        file_results.append(
            result
        )

    # --------------------------------------------------------
    # 4. LEVEL 1
    # --------------------------------------------------------

    module_results = enrich_modules(
        graph
    )

    elapsed = (
        time.time()
        - start_time
    )

    # --------------------------------------------------------
    # 5. FINAL REPORT
    # --------------------------------------------------------

    successful_files = [
        result
        for result in file_results
        if result["status"] == "success"
    ]

    failed_files = [
        result
        for result in file_results
        if result["status"] == "failed"
    ]

    successful_modules = [
        result
        for result in module_results
        if result["status"] == "success"
    ]

    failed_modules = [
        result
        for result in module_results
        if result["status"] == "failed"
    ]

    total_file_enriched = sum(
        result.get(
            "enriched",
            0,
        )
        for result in successful_files
    )

    total_file_missed = sum(
        result.get(
            "missed",
            0,
        )
        for result in successful_files
    )

    total_module_enriched = sum(
        result.get(
            "enriched",
            0,
        )
        for result in successful_modules
    )

    total_module_missed = sum(
        result.get(
            "missed",
            0,
        )
        for result in successful_modules
    )

    print()
    print("=" * 60)
    print(
        "FUSE COMPLETE"
    )
    print("=" * 60)

    print(
        f"Files discovered       : {len(files)}"
    )

    print(
        f"Files processed        : "
        f"{len(successful_files)}"
    )

    print(
        f"Files failed           : "
        f"{len(failed_files)}"
    )

    print(
        f"Modules processed      : "
        f"{len(successful_modules)}"
    )

    print(
        f"Modules failed         : "
        f"{len(failed_modules)}"
    )

    print(
        f"File/symbol enriched   : "
        f"{total_file_enriched}"
    )

    print(
        f"File/symbol missed     : "
        f"{total_file_missed}"
    )

    print(
        f"Module nodes enriched  : "
        f"{total_module_enriched}"
    )

    print(
        f"Module nodes missed    : "
        f"{total_module_missed}"
    )

    print(
        f"Time                   : "
        f"{elapsed:.1f}s"
    )

    print()
    print(
        "Output:"
    )

    print(
        "  data/code_graph.json"
    )

    print(
        "  data/enriched_code_graph.json"
    )

    print(
        "  data/summaries.json"
    )

    print(
        "  data/module_summaries.json"
    )

    print(
        "  data/enrichment_report.json"
    )

    # --------------------------------------------------------
    # FAILED FILES
    # --------------------------------------------------------

    if failed_files:

        print()
        print(
            "Failed files:"
        )

        for result in failed_files:

            print(
                f"  ✗ {result['file']}"
            )

            print(
                f"    {result['error']}"
            )

    # --------------------------------------------------------
    # FAILED MODULES
    # --------------------------------------------------------

    if failed_modules:

        print()
        print(
            "Failed modules:"
        )

        for result in failed_modules:

            print(
                f"  ✗ {result['module']}"
            )

            print(
                f"    {result['error']}"
            )


# ============================================================
# ENTRY POINT
# ============================================================

if __name__ == "__main__":
    run()