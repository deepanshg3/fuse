import json
import time
from pathlib import Path

from parser.build_graph import build_graph, export_graph

from summarizer.summarize_file import (
    summarize_file,
    save_summary,
)

from summarizer.summarize_module import (
    summarize_module,
    save_module_summary,
)

from graph.enrich_graph import (
    enrich_and_save,
    enrich_module_and_save,
    save_file_enrichment_report,
    save_module_enrichment_report,
)


# ============================================================
# CONFIG
# ============================================================

REPO_ROOT = Path(
    "test_repo/flask/src/flask"
)

MAX_RETRIES = 2


# ============================================================
# FILE DISCOVERY
# ============================================================

def discover_files():
    """
    Find all Python source files in the target repository.
    """

    return sorted(
        file
        for file in REPO_ROOT.rglob("*.py")
        if "__pycache__" not in file.parts
    )


# ============================================================
# GRAPH INITIALIZATION
# ============================================================

def initialize_graph():
    """
    Build the structural knowledge graph before
    semantic enrichment begins.
    """

    print(
        "[FUSE] Building structural knowledge graph..."
    )

    graph = build_graph(
        REPO_ROOT
    )

    export_graph(
        graph
    )

    print(
        f"[FUSE] Structural graph ready: "
        f"{graph.number_of_nodes()} nodes, "
        f"{graph.number_of_edges()} edges"
    )

    return graph


# ============================================================
# SYMBOL EXTRACTION
# ============================================================

def get_file_symbols(
    graph,
    file_path: Path,
):
    """
    Extract the exact symbols generated by Tree-sitter
    for one file.

    These symbols are passed to Gemini so Gemini only
    describes symbols that actually exist in the graph.
    """

    relative_path = str(
        file_path.relative_to(
            REPO_ROOT
        )
    )

    symbols = []

    for node_id, data in graph.nodes(
        data=True
    ):

        node_type = data.get(
            "type"
        )

        if node_type not in {
            "class",
            "function",
            "method",
        }:
            continue

        if data.get("file") != relative_path:
            continue

        symbols.append({
            "name": data.get("name"),
            "type": node_type,
            "parent": data.get(
                "parent",
                "",
            ),
            "line": data.get("line"),
            "end_line": data.get(
                "end_line"
            ),
        })

    return symbols


# ============================================================
# FILE SUMMARIZATION
# LEVEL 2 + LEVEL 3
# ============================================================

def process_file(
    file_path: Path,
    index: int,
    total: int,
    graph,
):
    """
    Generate Level 2 file summary and Level 3 symbol
    descriptions, then enrich the graph.
    """

    relative_path = file_path.relative_to(
        REPO_ROOT
    )

    print(
        f"[{index}/{total}] "
        f"Gemini → {relative_path}",
        end=" ",
        flush=True,
    )

    # --------------------------------------------------------
    # TREE-SITTER SYMBOLS
    # --------------------------------------------------------

    symbols = get_file_symbols(
        graph,
        file_path,
    )

    last_error = None

    # --------------------------------------------------------
    # RETRY
    # --------------------------------------------------------

    for attempt in range(
        1,
        MAX_RETRIES + 1,
    ):

        try:

            # ------------------------------------------------
            # GEMINI — LEVEL 2 + LEVEL 3
            # ------------------------------------------------

            result = summarize_file(
                file_path,
                symbols,
            )

            # ------------------------------------------------
            # SAVE FILE/SYMBOL SUMMARY
            # ------------------------------------------------

            save_summary(
                file_path,
                result,
            )

            # ------------------------------------------------
            # ENRICH FILE + SYMBOL NODES
            # ------------------------------------------------

            enrichment = enrich_and_save(
                str(relative_path),
                result,
            )

            # ------------------------------------------------
            # SAVE REPORT
            # ------------------------------------------------

            save_file_enrichment_report(
                str(relative_path),
                enrichment,
            )

            enriched = len(
                enrichment.get(
                    "enriched",
                    [],
                )
            )

            missed = len(
                enrichment.get(
                    "missed",
                    [],
                )
            )

            print(
                f"✓ "
                f"({enriched} enriched"
                f", {missed} missed)"
            )

            return {
                "status": "success",
                "file": str(
                    relative_path
                ),
                "enriched": enriched,
                "missed": missed,
                "attempts": attempt,
            }

        except Exception as error:

            last_error = error

            if attempt < MAX_RETRIES:

                print(
                    f"retry {attempt}...",
                    end=" ",
                    flush=True,
                )

                time.sleep(2)

            else:

                print(
                    f"✗ FAILED: {error}"
                )

    return {
        "status": "failed",
        "file": str(
            relative_path
        ),
        "error": str(
            last_error
        ),
        "attempts": MAX_RETRIES,
    }


# ============================================================
# MODULE DISCOVERY
# ============================================================

def get_modules(
    graph,
):
    """
    Return all module nodes from the structural graph.
    """

    modules = []

    for node_id, data in graph.nodes(
        data=True
    ):

        if data.get("type") != "module":
            continue

        modules.append(
            data.get("name")
        )

    return sorted(
        module
        for module in modules
        if module
    )


# ============================================================
# FILE SUMMARIES FOR MODULE
# ============================================================

def get_module_file_summaries(
    graph,
    module_name,
    summaries,
):
    """
    Collect the already-generated Level 2 file summaries
    belonging to one module.
    """

    file_summaries = []

    for node_id, data in graph.nodes(
        data=True
    ):

        if data.get("type") != "file":
            continue

        if data.get("module") != module_name:
            continue

        file_path = data.get(
            "path"
        )

        if file_path not in summaries:
            continue

        file_summary = summaries[
            file_path
        ]

        file_summaries.append({
            "path": file_path,
            "summary": file_summary.get(
                "file_summary",
                "",
            ),
        })

    return file_summaries


# ============================================================
